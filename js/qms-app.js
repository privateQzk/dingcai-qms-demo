      pubCols(tpl) {
        if (!tpl || tpl['是否使用公用参数'] !== '是') return 0;
        return tpl['公用测试次数'] === '同测试次数' ? (SOL_CALIB.sampCols(tpl) || 1) : 1;
      },
      matrices(tpl) {
        const out = [];
        const pc = SOL_CALIB.pubCols(tpl), sc = SOL_CALIB.sampCols(tpl);
        if (pc && (tpl._pubParams || []).length) out.push({ key: 'pub', label: '公共参数', cols: pc, params: tpl._pubParams });
        if (sc && (tpl._sampParams || []).length) out.push({ key: 'samp', label: '样本参数', cols: sc, params: tpl._sampParams });
        return out;
      },
      ensure(tpl, data) {
        data = data || {};
        ['env', 'dev', 'std', 'pub', 'samp'].forEach(k => { if (!data[k] || typeof data[k] !== 'object') data[k] = {}; });
        SOL_CALIB.groups(tpl).forEach(g => g.fields.forEach(f => { if (data[g.key][f['字段名称']] == null) data[g.key][f['字段名称']] = ''; }));
        SOL_CALIB.matrices(tpl).forEach(mx => mx.params.forEach(p => {
          const arr = Array.isArray(data[mx.key][p['参数编码']]) ? data[mx.key][p['参数编码']].slice() : [];
          while (arr.length < mx.cols) arr.push('');
          data[mx.key][p['参数编码']] = arr;
        }));
        if (data['备注'] == null) data['备注'] = '';
        return data;
      },
      bySymbol(tpl, sym) {
        for (const key of ['samp', 'pub']) {
          const p = ((key === 'samp' ? tpl._sampParams : tpl._pubParams) || []).find(x => x['参数代号'] === sym);
          if (p) return { p, key };
        }
        return null;
      },
      cell(tpl, data, p, key, i, depth) {
        if ((depth || 0) > 8) return NaN;
        if (p['计算公式']) {
          const expr = String(p['计算公式']).replace(/^=/, '').replace(/\{([^}]+)\}/g, (_, sym) => {
            const hit = SOL_CALIB.bySymbol(tpl, sym);
            const v = hit ? SOL_CALIB.cell(tpl, data, hit.p, hit.key, i, (depth || 0) + 1) : NaN;
            return Number.isFinite(v) ? '(' + v + ')' : 'NaN';
          });
          if (!/^[\d.+\-*/()\seNa]*$/.test(expr)) return NaN;
          try { const v = Function('return (' + expr + ')')(); return Number.isFinite(v) ? v : NaN; } catch (e) { return NaN; }
        }
        const cols = key === 'pub' ? SOL_CALIB.pubCols(tpl) : SOL_CALIB.sampCols(tpl);
        const raw = (((data || {})[key] || {})[p['参数编码']] || [])[Math.min(i, Math.max(cols - 1, 0))];
        if (raw === '' || raw == null) return NaN;
        const v = Number(raw);
        return Number.isFinite(v) ? v : NaN;
      },
      refValues(tpl, data) {
        if (!tpl) return [];
        for (const mx of SOL_CALIB.matrices(tpl)) {
          const p = mx.params.find(x => x['参数名称'] === tpl['结果值参考参数']);
          if (p) return Array.from({ length: mx.cols }, (_, i) => SOL_CALIB.cell(tpl, data, p, mx.key, i));
        }
        return [];
      },
      stats(vals) {
        if (!vals.length || vals.some(v => !Number.isFinite(v))) return null;
        const avg = vals.reduce((s, v) => s + v, 0) / vals.length;
        if (!avg) return null;
        return { avg: avg.toFixed(4), rr: ((Math.max(...vals) - Math.min(...vals)) / Math.abs(avg) * 100).toFixed(2) };
      },
      pass(rr, sym, std) {
        const a = parseFloat(rr), b = parseFloat(std);
        if (!Number.isFinite(a) || !Number.isFinite(b)) return false;
        return (sym === '＜' || sym === '<') ? a < b : a <= b;
      },
      stdText(sym, std) { return (std !== '' && std != null) ? ((sym || '≤') + std + '%') : ''; },
      result(tpl, data) {
        const s = tpl ? SOL_CALIB.stats(SOL_CALIB.refValues(tpl, data)) : null;
        if (!s) return { 平均值: '', 相对极差: '', 测试结论: '' };
        return { 平均值: s.avg, 相对极差: s.rr + '%', 测试结论: SOL_CALIB.pass(s.rr, tpl['单人极差符号'], tpl['单人测试相对极差合格标准']) ? '成功' : '失败' };
      },
      fmt(v) { return Number.isFinite(v) ? String(+v.toFixed(5)) : ''; },
      enumOpts(f) { return String((f && f['枚举内容']) || '').split(',').map(s => s.trim()).filter(Boolean); }
