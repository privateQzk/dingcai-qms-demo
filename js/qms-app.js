      const min = /(\d+)\s*分钟/.exec(src);
      if (day) hours += parseInt(day[1], 10) * 24;
      if (hour) hours += parseInt(hour[1], 10);
      if (min) hours += parseInt(min[1], 10) / 60;
      if (!hours) hours = parseInt(src, 10) || (job && job.noInst ? 0 : 1);
