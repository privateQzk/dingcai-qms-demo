    function confirmSplitPick() {
      const ids = qms.splitPickIds || [];
      if (!ids.length) { toast('请至少选择一条数据'); return; }
      const bad = [];
      const ok = [];
      splitCandidates().forEach(p => {
        if (ids.indexOf(p.id) < 0) return;
        const reason = splitBlockReason(p);
        if (reason) bad.push('样品 ' + p['样品编号'] + ' 不可拆分：' + reason);
        else ok.push(p.id);
      });
      if (bad.length && !ok.length) { toast(bad[0]); return; }
      if (bad.length) toast(bad[0]);
      qms.splitParentIds = ok.length ? ok : ids.filter(id => splitCandidates().some(p => p.id === id && !splitBlockReason(p)));
      if (!qms.splitParentIds.length) { toast('请至少选择一条数据'); return; }
      qms.splitLines = [];
      qms.mode = 'split';
    }
    function renumberSplitLines() {
      const seqMap = {};
      splitParents().forEach(p => { seqMap[p['样品编号']] = splitNextSeq(p); });
      qms.splitLines.forEach(l => {
        const no = l.母样编号;
        if (!seqMap[no]) seqMap[no] = 1;
        l.样品编号 = no + '-' + (seqMap[no]++);
      });
    }
    function genSplitLines() {
      const parents = splitParents();
      if (!parents.length) { toast('请先选择样品编号'); return; }
      const n = parseInt(qms.splitCount, 10);
      if (!/^\d+$/.test(String(qms.splitCount).trim()) || n < 1) { toast('拆分份数需为≥1的正整数'); return; }
      for (let i = 0; i < parents.length; i++) {
        const reason = splitBlockReason(parents[i]);
        if (reason) { toast('样品 ' + parents[i]['样品编号'] + ' 不可拆分：' + reason); return; }
      }
      const lines = [];
      parents.forEach(p => {
        const cassette = p['卡塞信息'] && p['卡塞信息'] !== '—' ? p['卡塞信息'] : '';
        for (let i = 0; i < n; i++) {
          lines.push({
            样品编号: '',
            母样编号: p['样品编号'],
            物料名称: p['物料名称'] || '',
            报检批号: p['报检批号'] || '',
            检验方案: p['检验方案'] || '',
            检验班组: p['检验班组'] || '',
            拆分备注: qms.splitRemark || '',
            卡塞信息: cassette,
            _picked: false,
            _parentId: p.id
          });
        }
      });
      qms.splitLines = lines;
      renumberSplitLines();
    }
